#!/usr/bin/env python3
"""Generate Claude-native subagent type definitions from the models.conf catalog.

`CFG_NATIVE_AGENT_CATALOG` (adapters/claude/config/models.conf) maps each native
subagent type to one portable execution profile. This generator resolves every
profile through `utilities/model_profile.py` and writes the agent-definition
files under `adapters/claude/agents/` with model AND effort pinned together —
the Agent tool input schema has no effort field, so a definition-file pin is
the only surface that can fix a native subagent's effort (core/ADAPTATION.md §3
"generated agent" derivation).

`general-purpose` deliberately shadows the runtime built-in of the same name
(user-scope definitions override built-ins). Its body below reproduces the
built-in system prompt verbatim (extracted from Claude Code 2.1.220) so the
override changes only the model/effort pin, never behavior. `light`/`deep` are
harness-owned types whose budgets align with the portable light/deep profiles.

The kernel helper `memory-scout` stays hand-authored (harness-manifest kernel
agent, guard-exempted); this generator owns only the catalog types. The shared
renderer in `utilities/native_agents.py` plans, generates and checks them.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Mapping, Optional

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "utilities"))

import native_agents  # noqa: E402
from model_profile import resolve_profile_values  # noqa: E402

GENERATED_MARK = ("# GENERATED by adapters/claude/bin/sync-native-agents.py from "
                  "adapters/claude/config/models.conf — do not hand-edit; "
                  "run tools/generate.py")

# The built-in general-purpose system prompt, verbatim (Claude Code 2.1.220).
# The override must not drift behavior — only the frontmatter model/effort pin
# is the point of shadowing the built-in.
_BUILTIN_GP_PROMPT = """\
You are an agent for Claude Code, Anthropic's official CLI for Claude. Given the user's message, you should use the tools available to complete the task. Complete the task fully—don't gold-plate, but don't leave it half-done. When you complete the task, respond with a concise report covering what was done and any key findings — the caller will relay this to the user, so it only needs the essentials.
Your strengths:
- Searching for code, configurations, and patterns across large codebases
- Analyzing multiple files to understand system architecture
- Investigating complex questions that require exploring many files
- Performing multi-step research tasks
Guidelines:
- For file searches: search broadly when you don't know where something lives. Use Read when you know the specific file path.
- For analysis: Start broad and narrow down. Use multiple search strategies if the first doesn't yield results.
- Be thorough: Check multiple locations, consider different naming conventions, look for related files.
- NEVER create files unless they're absolutely necessary for achieving your goal. ALWAYS prefer editing an existing file to creating a new one.
- NEVER proactively create documentation files (*.md) or README files. Only create documentation files if explicitly requested.
- You are already the dedicated agent for this task. Do the work directly — do not re-delegate your entire assignment to another single subagent.\
"""

_BUILTIN_GP_DESCRIPTION = (
    "General-purpose agent for researching complex questions, searching for code, "
    "and executing multi-step tasks. When you are searching for a keyword or file "
    "and are not confident that you will find the right match in the first few "
    "tries use this agent to perform the search for you."
)

CATALOG_AGENTS = {
    "balanced": {
        "description": "Execute an approved decision across multiple steps on the balanced budget.",
        "body": """Carry out the approved execution scope and cite its decision handoff.
Stop and return new important choices or uncertainty to the judgment owner.
Do not make architecture or policy decisions, widen scope, or spawn further agents.
Report completed steps, verification and remaining gaps.
""",
    },
    "general-purpose": {
        "description": _BUILTIN_GP_DESCRIPTION,
        "body": _BUILTIN_GP_PROMPT,
    },
    "light": {
        "description": (
            "Breadth fan-out subagent on the portable light budget. Default for "
            "parallel sweeps, audits, comparisons, and routine searches where "
            "several legs run at once. Prefer deep for a single hardest-leg "
            "investigation."
        ),
        "body": _BUILTIN_GP_PROMPT + """

You run as one leg of a breadth fan-out on a light execution budget:
- Stay inside the assigned slice; do not widen scope to neighboring questions.
- Return compact, deduplicated findings — the caller merges many legs, so
  every line must earn its place.
- Do not spawn further subagents; escalate by reporting, not by delegating.\
""",
    },
    "deep": {
        "description": (
            "Deep investigation subagent on the portable deep budget. Single "
            "hardest-leg analysis: root cause, architecture, subtle correctness. "
            "Prefer light for breadth fan-outs."
        ),
        "body": _BUILTIN_GP_PROMPT + """

You run as the deep leg of an investigation on the deep execution budget:
- Ground every claim in files you actually read; quote paths and lines.
- Distinguish verified facts from inference, and state residual uncertainty
  explicitly rather than smoothing it over.
- Prefer one airtight answer over broad partial coverage.\
""",
    },
}


def render_agent(name: str, profile: str, cfg: Mapping[str, str]) -> tuple[str, str]:
    spec = CATALOG_AGENTS.get(name)
    if spec is None:
        raise native_agents.RenderError(f"catalog names an agent with no defined spec: {name}")
    resolved = resolve_profile_values("claude", cfg, profile)
    if resolved["budget_kind"] != "effort":
        raise native_agents.RenderError(f"unexpected budget kind for {name}: {resolved['budget_kind']}")
    return f"""---
name: {name}
description: "{spec['description']}"
{GENERATED_MARK}
# profile: {profile} (tier {resolved['tier']})
model: {resolved['model']}
effort: {resolved['budget']}
---

{spec['body']}
""", resolved["model"]


def render(name: str, profile: Optional[str], cfg: Mapping[str, str]) -> tuple[str, Optional[str]]:
    if profile is None:
        raise native_agents.RenderError(f"{name} is hand-authored, not generated")
    return render_agent(name, profile, cfg)


FORMAT = native_agents.Format(
    adapter="claude",
    kernel_names=(),
    static_names=("memory-scout",),
    shipped_relpath=lambda name: f"{name}.md",
    dest_name=lambda name: f"{name}.md",
    render=render,
    collect_glob=None,  # the directory also holds the hand-written memory-scout.md
)


if __name__ == "__main__":
    sys.exit(native_agents.main(FORMAT, sys.argv[1:]))
